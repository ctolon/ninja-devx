from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src"
OUTPUT = ROOT / "docs" / "options"
HEADER = "<!-- Generated by tools/generate_docs.py from the source code; do not edit. -->\n\n"


# --- Reading the source ------------------------------------------------------------------


def _module_path(module: str) -> Path:
    base = SOURCE / Path(*module.split("."))
    return base / "__init__.py" if base.is_dir() else base.with_suffix(".py")


_trees: dict[str, ast.Module] = {}


def _tree(module: str) -> ast.Module:
    if module not in _trees:
        _trees[module] = ast.parse(_module_path(module).read_text())
    return _trees[module]


def _find(module: str, qualname: str) -> ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef:
    nodes: Sequence[ast.stmt] = _tree(module).body
    found: ast.stmt | None = None
    for part in qualname.split("."):
        matches = [
            node
            for node in nodes
            if isinstance(node, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef)
            and node.name == part
        ]
        found = matches[-1] if matches else None  # the implementation after any @overload
        if found is None:
            raise LookupError(f"{module}:{qualname} not found")
        nodes = found.body if isinstance(found, ast.ClassDef) else []
    assert isinstance(found, ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef)
    return found


def _rst(text: str) -> str:
    """RST-ish docstring text as one Markdown line."""
    text = re.sub(r"``([^`]+)``", r"`\1`", text)
    text = re.sub(r":(?:class|func|meth|attr):`~?([^`]+)`", r"`\1`", text)
    return " ".join(text.split())


def _paragraph(doc: str | None) -> str:
    if not doc:
        return ""
    return _rst(inspect.cleandoc(doc).split("\n\n")[0])


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{_cell(text)}`" if text else ""


def _unwrap_classvar(annotation: ast.expr) -> ast.expr:
    if (
        isinstance(annotation, ast.Subscript)
        and isinstance(annotation.value, ast.Name)
        and annotation.value.id in {"ClassVar", "Final"}
    ):
        return annotation.slice
    return annotation


def _attribute_doc(body: Sequence[ast.stmt], index: int) -> str:
    following = body[index + 1] if index + 1 < len(body) else None
    if (
        isinstance(following, ast.Expr)
        and isinstance(following.value, ast.Constant)
        and isinstance(following.value.value, str)
    ):
        return _paragraph(following.value.value)
    return ""


@dataclass
class Attribute:
    name: str
    type: str
    default: str
    doc: str


def attributes(module: str, qualname: str, *, public_only: bool = True) -> list[Attribute]:
    node = _find(module, qualname)
    assert isinstance(node, ast.ClassDef)
    found: list[Attribute] = []
    for index, statement in enumerate(node.body):
        if not (isinstance(statement, ast.AnnAssign) and isinstance(statement.target, ast.Name)):
            continue
        name = statement.target.id
        if public_only and name.startswith("_"):
            continue
        default = ast.unparse(statement.value) if statement.value is not None else ""
        found.append(
            Attribute(
                name,
                ast.unparse(_unwrap_classvar(statement.annotation)),
                default,
                _attribute_doc(node.body, index),
            )
        )
    return found


def class_doc(module: str, qualname: str) -> str:
    return _paragraph(ast.get_docstring(_find(module, qualname)))


@dataclass
class Parameter:
    name: str
    type: str
    default: str
    kind: str
    doc: str


def _param_docs(doc: str | None) -> dict[str, str]:
    found: dict[str, str] = {}
    if not doc:
        return found
    current: str | None = None
    for line in inspect.cleandoc(doc).splitlines():
        if match := re.match(r"\s*:param (\*{0,2}\w+):\s*(.*)", line):
            current = match.group(1).lstrip("*")
            found[current] = match.group(2)
        elif current and line.startswith((" ", "\t")) and line.strip():
            found[current] += " " + line.strip()
        else:
            current = None
    return {name: _rst(text) for name, text in found.items()}


def _description(doc: str | None) -> str:
    if not doc:
        return ""
    kept = [
        line
        for line in inspect.cleandoc(doc).split("\n\n")
        if not line.lstrip().startswith(":param")
    ]
    return _rst(kept[0]) if kept else ""


def parameters(module: str, qualname: str) -> tuple[list[Parameter], str, str]:
    node = _find(module, qualname)
    if isinstance(node, ast.ClassDef):
        init = next(
            (s for s in node.body if isinstance(s, ast.FunctionDef) and s.name == "__init__"), None
        )
        if init is None:
            raise LookupError(f"{qualname} has no __init__")
        function: ast.FunctionDef | ast.AsyncFunctionDef = init
        doc = ast.get_docstring(node) or ""
        init_doc = ast.get_docstring(init) or ""
        docs = {**_param_docs(doc), **_param_docs(init_doc)}
        summary = _description(doc)
    else:
        function = node
        doc = ast.get_docstring(node) or ""
        docs = _param_docs(doc)
        summary = _description(doc)
    arguments = function.args
    found: list[Parameter] = []
    positional = [*arguments.posonlyargs, *arguments.args]
    defaults: list[ast.expr | None] = [None] * (len(positional) - len(arguments.defaults)) + list(
        arguments.defaults
    )
    for index, (argument, default) in enumerate(zip(positional, defaults, strict=True)):
        if argument.arg in {"self", "cls"}:
            continue
        kind = "positional-only" if index < len(arguments.posonlyargs) else ""
        found.append(_parameter(argument, default, kind, docs))
    if arguments.vararg:
        found.append(_parameter(arguments.vararg, None, "*args", docs))
    for argument, default in zip(arguments.kwonlyargs, arguments.kw_defaults, strict=True):
        found.append(_parameter(argument, default, "keyword-only", docs))
    if arguments.kwarg:
        found.append(_parameter(arguments.kwarg, None, "**kwargs", docs))
    returns = ast.unparse(function.returns) if function.returns is not None else ""
    return found, summary, returns


def _parameter(
    argument: ast.arg, default: ast.expr | None, kind: str, docs: dict[str, str]
) -> Parameter:
    annotation = ast.unparse(argument.annotation) if argument.annotation is not None else ""
    return Parameter(
        argument.arg,
        annotation,
        ast.unparse(default) if default is not None else "",
        kind,
        docs.get(argument.arg, ""),
    )


# --- Blocks ------------------------------------------------------------------------------


class Block:
    def render(self) -> str:
        raise NotImplementedError


@dataclass
class Text(Block):
    markdown: str

    def render(self) -> str:
        return inspect.cleandoc(self.markdown) + "\n"


@dataclass
class Attributes(Block):
    """Class attributes, TypedDict keys or dataclass fields."""

    target: str
    title: str | None = None
    note: str = ""
    defaults: Callable[[str], str] | None = None
    exclude: Sequence[str] = ()
    required_label: bool = False

    def render(self) -> str:
        module, qualname = self.target.split(":")
        rows = [a for a in attributes(module, qualname) if a.name not in self.exclude]
        title = self.title or f"`{qualname}`"
        lines = [f"### {title}", ""]
        if doc := class_doc(module, qualname):
            lines += [doc, ""]
        if self.note:
            lines += [inspect.cleandoc(self.note), ""]
        lines += ["| Name | Type | Default | Description |", "|---|---|---|---|"]
        for row in rows:
            default = self.defaults(row.name) if self.defaults else row.default
            lines.append(
                f"| `{row.name}` | {_code(row.type)} | {_code(default) or '—'} | {_cell(row.doc)} |"
            )
        return "\n".join(lines) + "\n"


@dataclass
class Signature(Block):
    target: str
    title: str | None = None
    display: str | None = None

    def render(self) -> str:
        module, qualname = self.target.split(":")
        params, summary, returns = parameters(module, qualname)
        name = self.display or qualname.split(".")[-1]
        title = self.title or f"`{name}()`"
        lines = [f"### {title}", ""]
        signature = ", ".join(_signature_part(p) for p in _with_markers(params))
        arrow = f" -> {returns}" if returns else ""
        function = name.rsplit(".", 1)[-1]
        lines += ["```python", f"def {function}({signature}){arrow}: ...", "```", ""]
        if summary:
            lines += [summary, ""]
        if params:
            lines += ["| Parameter | Type | Default | Description |", "|---|---|---|---|"]
            for p in params:
                label = {"*args": f"*{p.name}", "**kwargs": f"**{p.name}"}.get(p.kind, p.name)
                lines.append(
                    f"| `{label}` | {_code(p.type)} | {_code(p.default) or '—'} | {_cell(p.doc)} |"
                )
        return "\n".join(lines) + "\n"


def _with_markers(params: list[Parameter]) -> list[Parameter | str]:
    parts: list[Parameter | str] = []
    slash_done = False
    star_done = any(p.kind == "*args" for p in params)
    for p in params:
        if (
            not slash_done
            and p.kind != "positional-only"
            and any(q.kind == "positional-only" for q in params)
        ):
            parts.append("/")
            slash_done = True
        if p.kind == "keyword-only" and not star_done:
            parts.append("*")
            star_done = True
        parts.append(p)
    return parts


def _signature_part(part: Parameter | str) -> str:
    if isinstance(part, str):
        return part
    prefix = {"*args": "*", "**kwargs": "**"}.get(part.kind, "")
    text = f"{prefix}{part.name}"
    if part.type:
        text += f": {part.type}"
    if part.default:
        text += f" = {part.default}" if part.type else f"={part.default}"
    return text


@dataclass
class Classes(Block):
    """A table of classes with their constructor arguments and summary."""

    title: str
    targets: Sequence[str]
    header: tuple[str, str, str] = ("Class", "Arguments", "Description")

    def render(self) -> str:
        lines = [f"### {self.title}", "", f"| {' | '.join(self.header)} |", "|---|---|---|"]
        for target in self.targets:
            module, qualname = target.split(":")
            try:
                params, summary, _ = parameters(module, qualname)
                arguments = ", ".join(_signature_part(p) for p in _with_markers(params))
            except LookupError:
                fields = attributes(module, qualname)
                arguments = ", ".join(
                    f"{a.name}: {a.type}" + (f" = {a.default}" if a.default else "")
                    for a in fields
                    if not a.doc.startswith("Set by")
                )
                summary = class_doc(module, qualname)
            summary = summary or class_doc(module, qualname)
            lines.append(f"| `{qualname}` | {_code(arguments) or '—'} | {_cell(summary)} |")
        return "\n".join(lines) + "\n"


@dataclass
class Runtime(Block):
    """A table computed by importing the package (errors, commands, fixtures)."""

    build: Callable[[], str]

    def render(self) -> str:
        return self.build()


@dataclass
class Page:
    slug: str
    title: str
    intro: str
    blocks: list[Block] = field(default_factory=list)

    def render(self) -> str:
        parts = [HEADER + f"# {self.title}\n", inspect.cleandoc(self.intro) + "\n"]
        parts += [block.render() for block in self.blocks]
        return "\n".join(parts)


