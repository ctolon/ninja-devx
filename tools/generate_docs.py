def _settings_default(name: str) -> str:
    module, qualname = "ninja_devx.configuration.settings", "ResolvedSettings"
    defaults = {a.name: a.default for a in attributes(module, qualname)}
    value = defaults.get(name.lower(), "")
    if "default_factory" in value:
        match = re.search(r"default_factory=(?:lambda: )?([^)]*)", value)
        inner = match.group(1) if match else ""
        return "{}" if "dict" in inner or inner.startswith("cast") else inner + "()"
    return value


def domain_errors() -> str:
    from ninja_devx.layers.errors import DomainError

    rows: dict[str, type[DomainError]] = {}
    for module_name in (
        "ninja_devx.layers.errors",
        "ninja_devx.layers.policies",
        "ninja_devx.security.tenancy",
        "ninja_devx.http.conditional",
    ):
        module = importlib.import_module(module_name)
        for value in vars(module).values():
            if isinstance(value, type) and issubclass(value, DomainError):
                rows[f"{value.__module__}.{value.__qualname__}"] = value
    lines = [
        "### Built-in domain errors",
        "",
        "| Exception | Status | `code` | Default `detail` | Import |",
        "|---|---|---|---|---|",
    ]
    for _path, error in sorted(rows.items(), key=lambda item: (item[1].http_status, item[0])):
        doc = inspect.cleandoc(error.__doc__ or "").split("\n")[0]
        module = (
            error.__module__.removesuffix(".errors")
            if "layers" in error.__module__
            else error.__module__
        )
        lines.append(
            f"| `{error.__qualname__}` | {error.http_status} | `{error.code}` | {_cell(doc)} | `{module}` |"
        )
    return "\n".join(lines) + "\n"


def exceptions_and_warnings() -> str:
    from ninja_devx import exceptions

    lines = ["### Exceptions and warnings", "", "| Class | Base | When |", "|---|---|---|"]
    classes = [
        value
        for value in vars(exceptions).values()
        if isinstance(value, type)
        and issubclass(value, BaseException)
        and value.__module__ == exceptions.__name__
    ]
    for value in classes:
        name = value.__qualname__
        base = value.__bases__[0].__name__
        lines.append(f"| `{name}` | `{base}` | {_cell(_paragraph(value.__doc__))} |")
    return "\n".join(lines) + "\n"


def management_command(name: str, app: str = "ninja_devx") -> Callable[[], str]:
    def build() -> str:
        from django.core.management import load_command_class

        command = load_command_class(app, name)
        parser = command.create_parser("manage.py", name)
        lines = [
            f"### `manage.py {name}`",
            "",
            _rst(command.help),
            "",
            "| Argument | Type | Default | Description |",
            "|---|---|---|---|",
        ]
        builtin = {
            "--version", "-v", "--verbosity", "--settings", "--pythonpath", "--traceback",
            "--no-color", "--force-color", "--skip-checks", "-h", "--help",
        }  # fmt: skip
        for action in parser._actions:
            flags = [flag for flag in action.option_strings if flag not in builtin]
            if action.option_strings and not flags:
                continue
            label = ", ".join(flags) if flags else action.dest
            kind = (
                "flag"
                if isinstance(action, argparse._StoreTrueAction)
                else "one of " + ", ".join(f"`{c}`" for c in action.choices)
                if action.choices
                else ("list" if action.nargs in ("+", "*") else "value")
            )
            default = (
                "" if action.default in (None, False, argparse.SUPPRESS) else repr(action.default)
            )
            if isinstance(action.default, str) and os.path.isabs(action.default):
                default = "the ninja-devx app template"  # machine-specific path
            lines.append(
                f"| `{label}` | {kind} | {_code(default) or '—'} | {_cell(action.help or '')} |"
            )
        return "\n".join(lines) + "\n"

    return build


def template_command(name: str, django_name: str) -> Callable[[], str]:
    # Django's startapp/startproject options (and their help texts) differ between Django
    # versions, so only the options ninja-devx adds are read from the parser.
    def build() -> str:
        from django.core.management import load_command_class

        command = load_command_class("ninja_devx", name)
        base = load_command_class("django.core", django_name).create_parser("manage.py", name)
        inherited = {action.dest for action in base._actions}
        lines = [
            f"### `manage.py {name}`",
            "",
            _rst(command.help),
            "",
            "| Argument | Type | Default | Description |",
            "|---|---|---|---|",
            f"| `name` | value | — | Name of the {django_name.removeprefix('start')}. |",
            "| `directory` | value | — | Optional destination directory, created if needed. |",
            "| `--template` | value | the ninja-devx template | Another template directory or archive. |",
        ]
        for action in command.create_parser("manage.py", name)._actions:
            if action.dest in inherited:
                continue
            kind = "flag" if isinstance(action, argparse._StoreTrueAction) else "value"
            label = ", ".join(action.option_strings)
            lines.append(f"| `{label}` | {kind} | — | {_cell(action.help or '')} |")
        lines += [
            "",
            f"Every other option of Django's `{django_name}` (`--extension`, `--name`, "
            "`--exclude`) is accepted.",
            "",
        ]
        return "\n".join(lines)

    return build


