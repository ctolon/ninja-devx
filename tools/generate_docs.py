def render_all() -> dict[Path, str]:
    rendered = {OUTPUT / f"{page.slug}.md": page.render() for page in pages()}
    metadata = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    classifiers = metadata["classifiers"]
    python_versions = [
        item.rsplit(" :: ", 1)[1]
        for item in classifiers
        if re.fullmatch(r"Programming Language :: Python :: \d+\.\d+", item)
    ]
    django_versions = [
        item.rsplit(" :: ", 1)[1]
        for item in classifiers
        if re.fullmatch(r"Framework :: Django :: \d+\.\d+", item)
    ]
    ninja = next(item for item in metadata["dependencies"] if item.startswith("django-ninja"))
    table = (
        "<!-- support-matrix:start -->\n"
        "| Component | Declared compatibility |\n|---|---|\n"
        f"| Python | {', '.join(python_versions)} |\n"
        f"| Django | {', '.join(django_versions)} |\n"
        f"| django-ninja | `{ninja}` |\n"
        "<!-- support-matrix:end -->"
    )
    support = ROOT / "docs" / "project" / "support.md"
    rendered[support] = re.sub(
        r"<!-- support-matrix:start -->.*?<!-- support-matrix:end -->",
        lambda match: table,
        support.read_text(),
        flags=re.DOTALL,
    )
    return rendered


def main(argv: Iterable[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(list(argv) if argv is not None else None)
    sys.path[:0] = [str(SOURCE), str(ROOT)]
    os.environ.setdefault("DJANGO_SETTINGS_MODULE", "tests.settings")
    import django

    django.setup()
    rendered = render_all()
    outdated = [
        path
        for path, content in rendered.items()
        if not path.exists() or path.read_text() != content
    ]
    if arguments.check:
        for path in outdated:
            print(f"outdated: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if outdated else 0
    OUTPUT.mkdir(parents=True, exist_ok=True)
    for path in outdated:
        path.write_text(rendered[path])
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
