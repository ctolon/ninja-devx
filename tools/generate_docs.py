"""Generate the configuration reference (``docs/options/*.md``) from the source code.

Every table (option, attribute, parameter, setting, command flag, error code) is read from
the code itself: types and defaults from the AST exactly as written, descriptions from
attribute docstrings and ``:param name:`` lines. The docs cannot drift from the code:
``tests/test_generated_docs.py`` fails when a page is outdated.

::

    uv run python tools/generate_docs.py          # write
    uv run python tools/generate_docs.py --check  # CI
"""

from __future__ import annotations

