_IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")

_UPLOAD_TYPE = """\
class UploadFile(NamedTuple):
    filename: str
    content: bytes
    content_type: str = "application/octet-stream"
"""

_COOKIE_RUNTIME = """\
def _cookie_header(values: Mapping[str, object]) -> str | None:
    parts = [f"{name}={value}" for name, value in values.items() if value is not None]
    return "; ".join(parts) or None
"""

_MULTIPART_RUNTIME = """\
def _multipart(body: object) -> tuple[dict[str, str], dict[str, tuple[str, bytes, str]]]:
    values = _multipart_values(body)
    fields: dict[str, str] = {}
    files: dict[str, tuple[str, bytes, str]] = {}
    for name, value in values.items():
        if value is None:
            continue
        if isinstance(value, UploadFile):
            files[name] = (value.filename, value.content, value.content_type)
        elif isinstance(value, bytes):
            files[name] = (name, value, "application/octet-stream")
        elif isinstance(value, str | int | float | bool):
            fields[name] = str(value).lower() if isinstance(value, bool) else str(value)
        else:
            raise TypeError(f"Unsupported multipart value for {name!r}")
    return fields, files
"""

_RUNTIME = """\
class ApiError(Exception):
    def __init__(
        self, status_code: int, body: object, headers: Mapping[str, str] | None = None
    ) -> None:
        super().__init__(f"Request failed with status {status_code}")
        self.status_code = status_code
        self.body = body
        self.headers = dict(headers or {})


_Primitive = str | int | float | bool | None


def _query(values: Mapping[str, object]) -> dict[str, _Primitive | list[_Primitive]]:
    return {
        key: cast("_Primitive | list[_Primitive]", value)
        for key, value in values.items()
        if value is not None
    }


def _path(value: object) -> str:
    return quote(str(value), safe="")


def _header_value(value: object) -> str:
    return str(value).lower() if isinstance(value, bool) else str(value)


def _headers(
    values: Mapping[str, object], extra: Mapping[str, str] | None, *, multipart: bool = False
) -> httpx.Headers:
    headers = httpx.Headers(extra)
    for name, value in values.items():
        if value is not None:
            headers[name] = (
                ",".join(_header_value(item) for item in value)
                if isinstance(value, list | tuple) else _header_value(value)
            )
    if multipart and "Content-Type" in headers:
        del headers["Content-Type"]
    return headers


def _decode(response: httpx.Response) -> object:
    media_type = response.headers.get("Content-Type", "").split(";", 1)[0].lower()
    body: object = None
    if response.content:
        if media_type == "application/json" or media_type.endswith("+json"):
            try:
                body = response.json()
            except ValueError:
                raise ApiError(response.status_code, response.text, response.headers) from None
        elif media_type.startswith("text/") or not response.is_success:
            body = response.text
        else:
            body = response.content
    if not response.is_success:
        raise ApiError(response.status_code, body, response.headers)
    return body
"""


def generate_python(
    document: Schema,
    *,
    class_name: str = "ApiClient",
    style: Literal["pydantic", "typeddict"] = "pydantic",
) -> str:
    document = named_multipart_bodies(document)
    _validate(document, class_name=class_name, style=style)
    if style == "pydantic":
        return _generate_pydantic(document, class_name=class_name)
    info = _mapping(document.get("info"))
    operations = read_operations(document)
    parts = [
        "# ruff: noqa: E501",
        _source.literal(
            f"Generated by ninja-devx from {info.get('title', 'API')} "
            f"{info.get('version', '')}. Do not edit."
        ),
        "",
        "from __future__ import annotations",
        "",
        _collections_import(operations),
        "from typing import Literal, NamedTuple, NotRequired, TypedDict, cast",
        "from urllib.parse import quote",
        "",
        "import httpx",
        "",
        '__all__ = ["ApiError", "UploadFile", "Async' + class_name + '", "' + class_name + '"]',
        "",
        "",
    ]
    parts.extend([_UPLOAD_TYPE, ""])
    schemas = _mapping(_mapping(document.get("components")).get("schemas"))
    for name, schema in schemas.items():
        parts.append(_declaration(name, _mapping(schema)))
        parts.append("")
    parts.append(_RUNTIME)
    parts.append(
        "def _multipart_values(body: object) -> Mapping[str, object]:\n"
        '    return cast("Mapping[str, object]", body or {})\n'
    )
    parts.append(_MULTIPART_RUNTIME)
    if _uses_cookies(operations):
        parts.append(_COOKIE_RUNTIME)
    parts.append(_client(class_name, operations, asynchronous=False))
    parts.append(_client(f"Async{class_name}", operations, asynchronous=True))
    source = "\n".join(parts)
    return _checked(source)


def _declaration(name: str, schema: Schema) -> str:
    properties = _mapping(schema.get("properties"))
    if not (schema.get("type") == "object" and properties):
        return f"{name} = {py_type(schema, quote_refs=False)}\n"
    required = set(_strings(schema.get("required")))
    items = [
        (
            key,
            py_type(_mapping(value))
            if key in required
            else f"NotRequired[{py_type(_mapping(value))}]",
        )
        for key, value in properties.items()
    ]
    if all(_IDENTIFIER.match(key) and not keyword.iskeyword(key) for key, _ in items):
        body = "\n".join(f"    {key}: {annotation}" for key, annotation in items)
        return f"class {name}(TypedDict):\n{body}\n"
    fields = ", ".join(
        f"{_source.literal(key)}: {_source.literal(annotation)}" for key, annotation in items
    )
    return f'{name} = TypedDict("{name}", {{{fields}}})\n'


def py_type(schema: Schema, *, quote_refs: bool = False) -> str:
    if schema.get("format") == "binary" and not schema.get("x-binary-response"):
        return "UploadFile | bytes"
    if schema.get("x-binary-response"):
        return "bytes"
    if "$ref" in schema:
        name = ref_name(str(schema["$ref"]))
        return f'"{name}"' if quote_refs else name
    for combinator in ("anyOf", "oneOf"):
        if combinator in schema:
            members = list(
                dict.fromkeys(
                    py_type(_mapping(item), quote_refs=quote_refs)
                    for item in _list(schema[combinator])
                )
            )
            return " | ".join(members)
    if "allOf" in schema:
        parts = _list(schema["allOf"])
        return (
            py_type(_mapping(parts[0]), quote_refs=quote_refs)
            if len(parts) == 1
            else "dict[str, object]"
        )
    if "enum" in schema:
        values = ", ".join(
            _source.literal(v) if isinstance(v, str) else repr(v) for v in _list(schema["enum"])
        )
        return f"Literal[{values}]"
    kind = schema.get("type")
    if kinds := _list(kind):
        return " | ".join(
            py_type({**schema, "type": item}, quote_refs=quote_refs) for item in kinds
        )
    simple = {
        "string": "str",
        "integer": "int",
        "number": "float",
        "boolean": "bool",
        "null": "None",
    }
    if isinstance(kind, str) and kind in simple:
        return simple[kind]
    if kind == "array":
        return f"list[{py_type(_mapping(schema.get('items')), quote_refs=quote_refs)}]"
    extra = schema.get("additionalProperties")
    if extra_schema := _mapping(extra):
        return f"dict[str, {py_type(extra_schema, quote_refs=quote_refs)}]"
    return "dict[str, object]" if kind == "object" else "object"


def _client(name: str, operations: list[Operation], *, asynchronous: bool) -> str:
    http = "httpx.AsyncClient" if asynchronous else "httpx.Client"
    lines = [
        f"class {name}:",
        f'    """{"Async client" if asynchronous else "Client"} for the API."""',
        "",
        "    def __init__(",
        "        self,",
        '        base_url: str = "",',
        "        *,",
        f"        client: {http} | None = None,",
        "        headers: Mapping[str, str] | None = None,",
        "    ) -> None:",
        f"        self._client = client or {http}(base_url=base_url, headers=headers)",
        "",
    ]
    if asynchronous:
        lines += [
            "    async def aclose(self) -> None:",
            "        await self._client.aclose()",
            "",
            f"    async def __aenter__(self) -> {name}:",
            "        return self",
            "",
            "    async def __aexit__(self, *exc_info: object) -> None:",
            "        await self.aclose()",
            "",
        ]
    else:
        lines += [
            "    def close(self) -> None:",
            "        self._client.close()",
            "",
            f"    def __enter__(self) -> {name}:",
            "        return self",
            "",
            "    def __exit__(self, *exc_info: object) -> None:",
            "        self.close()",
            "",
        ]
    for operation in operations:
        lines += _method(operation, asynchronous=asynchronous)
    return "\n".join(lines)


def _declared_headers(header_params: list[Parameter], cookie_params: list[Parameter]) -> str:
    entries = [f"{_source.literal(p.name)}: {_identifier(p.name)}" for p in header_params]
    if cookie_params:
        cookies = ", ".join(
            f"{_source.literal(p.name)}: {_identifier(p.name)}" for p in cookie_params
        )
        entries.append(f'"Cookie": _cookie_header({{{cookies}}})')
    return "{" + ", ".join(entries) + "}"


def _method(operation: Operation, *, asynchronous: bool) -> list[str]:
    if operation.streaming:
        return _stream_method(operation, asynchronous=asynchronous, pydantic=False)
    path_params = [p for p in operation.parameters if p.location == "path"]
    query_params = [p for p in operation.parameters if p.location == "query"]
    header_params = [p for p in operation.parameters if p.location == "header"]
    cookie_params = [p for p in operation.parameters if p.location == "cookie"]
    arguments = ["self"] + [f"{_identifier(p.name)}: {py_type(p.schema)}" for p in path_params]
    if operation.body is not None:
        default = "" if operation.body_required else " = None"
        body_type = py_type(operation.body) + ("" if operation.body_required else " | None")
        arguments.append(f"body: {body_type}{default}")
    keyword_only = [
        f"{_identifier(p.name)}: {py_type(p.schema)}" + ("" if p.required else " | None = None")
        for p in sorted(
            [*query_params, *header_params, *cookie_params], key=lambda p: not p.required
        )
    ]
    arguments.append("*")
    arguments.extend(keyword_only)
    arguments.extend(
        [
            "request_headers: Mapping[str, str] | None = None",
            "on_response: Callable[[httpx.Response], None] | None = None",
        ]
    )
    if operation.response is not None:
        result = py_type(operation.response)
    else:
        result = "object" if operation.has_body else "None"
    params = ", ".join(f"{_source.literal(p.name)}: {_identifier(p.name)}" for p in query_params)
    path_literal = _source.path_expression(
        operation.path, {p.name: _identifier(p.name) for p in path_params}
    )
    call_arguments = [f'"{operation.method}"', path_literal]
    if query_params:
        call_arguments.append(f"params=_query({{{params}}})")
    if operation.body is not None:
        if operation.body_media_type == "multipart/form-data":
            call_arguments.extend(["data=_form_data", "files=_form_files"])
        else:
            call_arguments.append("json=body")
    multipart = operation.body_media_type == "multipart/form-data"
    call_arguments.append(
        f"headers=_headers({_declared_headers(header_params, cookie_params)}, "
        f"request_headers, multipart={multipart})"
    )
    prefix = "async def" if asynchronous else "def"
    awaited = "await " if asynchronous else ""
    docstring = f"        {_source.literal(operation.summary)}" if operation.summary else None
    lines = _wrap(f"    {prefix} {_snake(operation.operation_id)}(", arguments, f") -> {result}:")
    if docstring:
        lines.append(docstring)
    if operation.body_media_type == "multipart/form-data":
        lines.append("        _form_data, _form_files = _multipart(body)")
    lines += _wrap(f"        response = {awaited}self._client.request(", call_arguments, ")")
    lines += ["        if on_response is not None:", "            on_response(response)"]
    if result == "None":
        lines.append("        _decode(response)")
    elif result == "object":
        lines.append("        return _decode(response)")
    else:
        lines.append(f'        return cast("{result}", _decode(response))')
    lines.append("")
    return lines


def _stream_method(operation: Operation, *, asynchronous: bool, pydantic: bool) -> list[str]:
    """A server-sent-events method yielding decoded lines from ``text/event-stream``."""
    type_fn = pydantic_type if pydantic else py_type
    path_params = [p for p in operation.parameters if p.location == "path"]
    query_params = [p for p in operation.parameters if p.location == "query"]
    header_params = [p for p in operation.parameters if p.location == "header"]
    cookie_params = [p for p in operation.parameters if p.location == "cookie"]
    arguments = ["self"] + [f"{_identifier(p.name)}: {type_fn(p.schema)}" for p in path_params]
    keyword_only = [
        f"{_identifier(p.name)}: {type_fn(p.schema)}" + ("" if p.required else " | None = None")
        for p in sorted(
            [*query_params, *header_params, *cookie_params], key=lambda p: not p.required
        )
    ]
    arguments.append("*")
    arguments.extend(keyword_only)
    arguments.append("request_headers: Mapping[str, str] | None = None")
    params = ", ".join(f"{_source.literal(p.name)}: {_identifier(p.name)}" for p in query_params)
    path_literal = _source.path_expression(
        operation.path, {p.name: _identifier(p.name) for p in path_params}
    )
    call_arguments = [f'"{operation.method}"', path_literal]
    if query_params:
        call_arguments.append(f"params=_query({{{params}}})")
    call_arguments.append(
        f"headers=_headers({_declared_headers(header_params, cookie_params)}, request_headers)"
    )
    prefix = "async def" if asynchronous else "def"
    result = "AsyncIterator[str]" if asynchronous else "Iterator[str]"
    lines = _wrap(f"    {prefix} {_snake(operation.operation_id)}(", arguments, f") -> {result}:")
    if operation.summary:
        lines.append(f"        {_source.literal(operation.summary)}")
    context = "async with" if asynchronous else "with"
    lines += _wrap(f"        {context} self._client.stream(", call_arguments, ") as response:")
    lines += [
        "            response.raise_for_status()",
        f"            {'async for' if asynchronous else 'for'} line in "
        f"response.{'aiter_lines' if asynchronous else 'iter_lines'}():",
        "                yield line",
        "",
    ]
    return lines


def _wrap(opening: str, items: list[str], closing: str) -> list[str]:
    """One line when it fits in 100 characters, else one item per line (ruff format style)."""
    line = f"{opening}{', '.join(items)}{closing}"
    if len(line) <= 100:
        return [line]
    indent = " " * (len(opening) - len(opening.lstrip()) + 4)
    return [opening, *(f"{indent}{item}," for item in items), f"{indent[:-4]}{closing}"]


def _snake(value: str) -> str:
    value = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", value)
    name = re.sub(r"[^0-9a-zA-Z]+", "_", value).strip("_").lower()
    if not name or name[0].isdigit():
        name = "operation_" + name
    return f"{name}_" if keyword.iskeyword(name) else name


def _collections_import(operations: Sequence[Operation]) -> str:
    names = ["Callable", "Mapping"]
    if any(operation.streaming for operation in operations):
        names = ["AsyncIterator", *names[:1], "Iterator", *names[1:]]
    return f"from collections.abc import {', '.join(names)}"


def _uses_cookies(operations: Sequence[Operation]) -> bool:
    return any(p.location == "cookie" for operation in operations for p in operation.parameters)


def _identifier(name: str) -> str:
    cleaned = re.sub(r"\W", "_", name)
    if not cleaned or cleaned[0].isdigit():
        cleaned = "parameter_" + cleaned
    reserved = {
        "self",
        "body",
        "query",
        "headers",
        "cookies",
        "files",
        "cast",
        "_path",
        "_query",
        "_jsonable",
        "_headers",
        "_header_value",
        "_cookie_header",
        "_multipart",
        "_multipart_values",
        "_form_data",
        "_form_files",
        "request_headers",
        "on_response",
    }
    return f"{cleaned}_" if keyword.iskeyword(cleaned) or cleaned in reserved else cleaned


