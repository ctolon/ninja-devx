"""Typed Python clients (``httpx``, sync and async) from an OpenAPI document.

Two model styles:

- ``"pydantic"`` (default): ``BaseModel`` classes with the schema's constraints as
  ``Field(...)`` (lengths, patterns, ranges), ``datetime``/``date``/``UUID`` formats,
  defaults, descriptions and aliases for names that aren't identifiers. Request bodies are
  validated before they are sent (``exclude_unset``, so partial updates stay partial) and
  responses are validated into models.
- ``"typeddict"``: ``TypedDict`` shapes with no runtime dependency beyond httpx.
"""

