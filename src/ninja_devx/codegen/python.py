def _generate_pydantic(document: Schema, *, class_name: str) -> str:
    info = _mapping(document.get("info"))
    operations = read_operations(document)
    parts = [
        "# ruff: noqa: E501, N815",
        _source.literal(
            f"Generated by ninja-devx from {info.get('title', 'API')} "
            f"{info.get('version', '')}. Do not edit."
        ),
        "",
        "from __future__ import annotations",
        "",
        "import datetime as _dt",
        "import uuid as _uuid",
        _collections_import(operations),
        "from typing import Annotated, Literal, NamedTuple, cast",
        "from urllib.parse import quote",
        "",
        "import httpx",
        "from pydantic import BaseModel as _BaseModel",
        "from pydantic import ConfigDict as _ConfigDict",
        "from pydantic import Field as _Field",
        "from pydantic import TypeAdapter as _TypeAdapter",
        "from pydantic_core import to_jsonable_python as _to_jsonable_python",
        "",
        '__all__ = ["ApiError", "UploadFile", "Async' + class_name + '", "' + class_name + '"]',
        "",
        "",
    ]
    parts.extend([_UPLOAD_TYPE, ""])
    schemas = _mapping(_mapping(document.get("components")).get("schemas"))
    for name, schema in schemas.items():
        parts.append(_model(name, _mapping(schema)))
        parts.append("")
    parts.append(_PYDANTIC_RUNTIME)
    parts.append("""def _multipart_values(body: object) -> Mapping[str, object]:
    if isinstance(body, _BaseModel):
        return {
            info.alias or name: getattr(body, name)
            for name, info in type(body).model_fields.items()
            if name in body.model_fields_set
        }
    return cast("Mapping[str, object]", body or {})
""")
    parts.append(_MULTIPART_RUNTIME)
    if _uses_cookies(operations):
        parts.append(_COOKIE_RUNTIME)
    adapters: dict[str, str] = {}
    sync_client = _pydantic_client(class_name, operations, adapters, asynchronous=False)
    async_client = _pydantic_client(f"Async{class_name}", operations, adapters, asynchronous=True)
    for annotation, name in adapters.items():
        parts.append(f"{name}: _TypeAdapter[{annotation}] = _TypeAdapter({annotation})")
    parts += ["", "", sync_client, async_client]
    source = "\n".join(parts)
    return _checked(source)


def pydantic_type(schema: Schema) -> str:
    if schema.get("format") == "binary" and not schema.get("x-binary-response"):
        return "UploadFile | bytes"
    """The annotation for ``schema`` in the pydantic style (formats become real types)."""
    if schema.get("x-binary-response"):
        return "bytes"
    if "$ref" in schema:
        return ref_name(str(schema["$ref"]))
    for combinator in ("anyOf", "oneOf"):
        if combinator in schema:
            members = list(
                dict.fromkeys(pydantic_type(_mapping(item)) for item in _list(schema[combinator]))
            )
            union = " | ".join(members)
            discriminator = _mapping(schema.get("discriminator"))
            property_name = discriminator.get("propertyName")
            if isinstance(property_name, str) and len(members) > 1:
                return f"Annotated[{union}, _Field(discriminator={_source.literal(property_name)})]"
            return union
    if "allOf" in schema:
        parts = _list(schema["allOf"])
        return pydantic_type(_mapping(parts[0])) if len(parts) == 1 else "dict[str, object]"
    if "enum" in schema:
        values = ", ".join(
            _source.literal(v) if isinstance(v, str) else repr(v) for v in _list(schema["enum"])
        )
        return f"Literal[{values}]"
    kind = schema.get("type")
    if kinds := _list(kind):
        return " | ".join(pydantic_type({**schema, "type": item}) for item in kinds)
    if kind == "string" and isinstance(schema.get("format"), str):
        return _FORMATS.get(str(schema["format"]), "str")
    if kind == "array":
        return f"list[{pydantic_type(_mapping(schema.get('items')))}]"
    if kind == "object" and (extra := _mapping(schema.get("additionalProperties"))):
        return f"dict[str, {pydantic_type(extra)}]"
    return py_type(schema)


def _model(name: str, schema: Schema) -> str:
    properties = _mapping(schema.get("properties"))
    if not (schema.get("type") == "object" and properties):
        if schema.get("type") == "object" or not schema:
            return f"{name} = dict[str, object]\n"
        return f"{name} = {pydantic_type(schema)}\n"
    required = set(_strings(schema.get("required")))
    lines = [f"class {name}(_BaseModel):"]
    if description := str(schema.get("description", "")).strip():
        lines.append(f"    {_source.literal(description)}")
        lines.append("")
    lines.append("    model_config = _ConfigDict(populate_by_name=True)")
    lines.append("")
    for key, raw in properties.items():
        value = _mapping(raw)
        attribute = _field_name(key)
        annotation = pydantic_type(value)
        arguments = _field_arguments(value)
        if attribute != key:
            arguments.insert(0, f"alias={_source.literal(key)}")
        default = ""
        if key not in required:
            if "default" in value:
                default = f" = {_python_literal(value['default'])}"
            else:
                if "None" not in annotation.split(" | "):
                    annotation = f"{annotation} | None"
                default = " = None"
        if arguments:
            annotation = f"Annotated[{annotation}, _Field({', '.join(arguments)})]"
        lines.append(f"    {attribute}: {annotation}{default}")
    return "\n".join(lines) + "\n"


def _field_arguments(schema: Schema) -> list[str]:
    arguments: list[str] = []
    members = [_mapping(item) for item in _list(schema.get("anyOf"))]
    non_null = [member for member in members if member.get("type") != "null"]
    if len(members) == 2 and len(non_null) == 1:  # ``T | None``: constraints live on ``T``
        schema = {**non_null[0], **{k: v for k, v in schema.items() if k != "anyOf"}}
    for keyword_name, argument in _CONSTRAINTS.items():
        value = schema.get(keyword_name)
        if isinstance(value, bool):
            continue
        if isinstance(value, int | float | str):
            arguments.append(f"{argument}={_python_literal(value)}")
    if description := str(schema.get("description", "")).strip():
        arguments.append(f"description={_source.literal(description)}")
    return arguments


def _field_name(key: str) -> str:
    name = re.sub(r"\W", "_", key)
    if not name or name[0].isdigit():
        name = f"field_{name}"
    if keyword.iskeyword(name) or name in _RESERVED or name.startswith(("model_", "_")):
        name = f"{name.lstrip('_')}_"
    return name


def _python_literal(value: object) -> str:
    if isinstance(value, str):
        return _source.literal(value)
    if isinstance(value, float) and not math.isfinite(value):
        raise ValueError("Non-finite defaults cannot be generated")
    if isinstance(value, bool) or value is None or isinstance(value, int | float):
        return repr(value)
    if isinstance(value, list | tuple):
        items: list[object] = list(cast("Sequence[object]", value))
        return "[" + ", ".join(_python_literal(item) for item in items) + "]"
    if isinstance(value, Mapping):
        entries = cast("Mapping[object, object]", value)
        return (
            "{"
            + ", ".join(
                f"{_source.literal(str(k))}: {_python_literal(v)}" for k, v in entries.items()
            )
            + "}"
        )
    raise ValueError(f"Unsupported default value type: {type(value).__name__}")


def _pydantic_client(
    name: str, operations: list[Operation], adapters: dict[str, str], *, asynchronous: bool
) -> str:
    lines = _client(name, [], asynchronous=asynchronous).split("\n")
    for operation in operations:
        lines += _pydantic_method(operation, adapters, asynchronous=asynchronous)
    return "\n".join(lines)


def _pydantic_method(
    operation: Operation, adapters: dict[str, str], *, asynchronous: bool
) -> list[str]:
    if operation.streaming:
        return _stream_method(operation, asynchronous=asynchronous, pydantic=True)
    path_params = [p for p in operation.parameters if p.location == "path"]
    query_params = [p for p in operation.parameters if p.location == "query"]
    header_params = [p for p in operation.parameters if p.location == "header"]
    cookie_params = [p for p in operation.parameters if p.location == "cookie"]
    arguments = ["self"] + [
        f"{_identifier(p.name)}: {pydantic_type(p.schema)}" for p in path_params
    ]
    if operation.body is not None:
        default = "" if operation.body_required else " = None"
        body_type = pydantic_type(operation.body) + ("" if operation.body_required else " | None")
        arguments.append(f"body: {body_type}{default}")
    keyword_only = [
        f"{_identifier(p.name)}: {pydantic_type(p.schema)}"
        + ("" if p.required else " | None = None")
        for p in sorted(
            [*query_params, *header_params, *cookie_params], key=lambda p: not p.required
        )
    ]
    arguments.append("*")
    arguments.extend(keyword_only)
    arguments.extend(
        [
            "request_headers: Mapping[str, str] | None = None",
            "on_response: Callable[[httpx.Response], None] | None = None",
        ]
    )
    if operation.response is not None:
        result = pydantic_type(operation.response)
    else:
        result = "object" if operation.has_body else "None"
    params = ", ".join(f"{_source.literal(p.name)}: {_identifier(p.name)}" for p in query_params)
    path_literal = _source.path_expression(
        operation.path, {p.name: _identifier(p.name) for p in path_params}
    )
    call_arguments = [f'"{operation.method}"', path_literal]
    if query_params:
        call_arguments.append(f"params=_query({{{params}}})")
    if operation.body is not None:
        if operation.body_media_type == "multipart/form-data":
            call_arguments.extend(["data=_form_data", "files=_form_files"])
        else:
            call_arguments.append("json=_jsonable(body)")
    multipart = operation.body_media_type == "multipart/form-data"
    call_arguments.append(
        f"headers=_headers({_declared_headers(header_params, cookie_params)}, "
        f"request_headers, multipart={multipart})"
    )
    prefix = "async def" if asynchronous else "def"
    awaited = "await " if asynchronous else ""
    lines = _wrap(f"    {prefix} {_snake(operation.operation_id)}(", arguments, f") -> {result}:")
    if operation.summary:
        lines.append(f"        {_source.literal(operation.summary)}")
    if operation.body_media_type == "multipart/form-data":
        lines.append("        _form_data, _form_files = _multipart(body)")
    lines += _wrap(f"        response = {awaited}self._client.request(", call_arguments, ")")
    lines += ["        if on_response is not None:", "            on_response(response)"]
    if result == "None":
        lines.append("        _decode(response)")
    elif result == "object":
        lines.append("        return _decode(response)")
    else:
        decoded = "_decode(response)"
        if len(operation.response_variants) > 1:
            lines.append("        decoded = _decode(response)")
            decoded = "decoded"
            for variant in operation.response_variants:
                if not variant.status.isdigit():
                    continue
                annotation = pydantic_type(variant.schema)
                adapter = adapters.setdefault(annotation, f"_RESULT_{len(adapters)}")
                condition = f"response.status_code == {int(variant.status)}"
                if variant.media_type is not None:
                    condition += (
                        ' and response.headers.get("Content-Type", "").split(";", 1)[0].lower() == '
                        + _source.literal(variant.media_type)
                    )
                lines.append(f"        if {condition}:")
                lines.append(f"            return {adapter}.validate_python(decoded)")
        adapter = adapters.setdefault(result, f"_RESULT_{len(adapters)}")
        lines.append(f"        return {adapter}.validate_python({decoded})")
    lines.append("")
    return lines


def _checked(source: str) -> str:
    source = re.sub(r"\n{3,}", "\n\n\n", source).rstrip() + "\n"
    ast.parse(source, filename="<generated Python client>")
    return source


def _validate(document: Schema, *, class_name: str, style: str) -> None:
    if style not in {"pydantic", "typeddict"}:
        raise ValueError(f"Unsupported Python model style: {style!r}")
    runtime = {
        "ApiError",
        "Mapping",
        "Literal",
        "TypedDict",
        "NotRequired",
        "Annotated",
        "cast",
        "httpx",
        "quote",
        "str",
        "int",
        "float",
        "bool",
        "list",
        "dict",
        "object",
        "Iterator",
        "AsyncIterator",
        "_BaseModel",
        "_TypeAdapter",
        "UploadFile",
        "NamedTuple",
        "_Field",
        "_ConfigDict",
        "_dt",
        "_uuid",
    }
    _source.identifier(class_name, reserved=runtime)
    _source.identifier("Async" + class_name, reserved=runtime)
    _source.schemas(document, reserved={*runtime, class_name, "Async" + class_name})
    operations = read_operations(document)
    _source.unique(
        (_snake(op.operation_id) for op in operations),
        namespace="client methods",
        reserved={
            "__init__",
            "__enter__",
            "__exit__",
            "__aenter__",
            "__aexit__",
            "close",
            "aclose",
            "_client",
        },
    )
    for op in operations:
        _source.unique(
            (
                _identifier(p.name)
                for p in op.parameters
                if p.location in {"path", "query", "header"}
            ),
            namespace=op.operation_id,
        )
    if style == "pydantic":
        for name, raw in _mapping(_mapping(document.get("components")).get("schemas")).items():
            properties = _mapping(_mapping(raw).get("properties"))
            _source.unique((_field_name(key) for key in properties), namespace=name)
