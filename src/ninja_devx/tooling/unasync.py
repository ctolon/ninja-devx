"""Generate the sync twin of async code, and check that it has not drifted.

Write the async implementation once; the sync one is derived token by token
(``async def`` → ``def``, ``await x`` → ``x``, ``async for/with`` → ``for/with``,
``aget`` → ``get``, ``AsyncIterator`` → ``Iterator``...)::

    python -m ninja_devx.tooling.unasync src/orders/aio.py:src/orders/sync.py
    python -m ninja_devx.tooling.unasync src/orders/aio.py:src/orders/sync.py --check   # CI
    python -m ninja_devx.tooling.unasync a.py:b.py --replace AsyncOrderRepository=OrderRepository

Names are replaced as whole tokens (strings and comments are left alone, except the
generated-file header). Django's async ORM methods, this package's ``a``-prefixed
helpers and the standard async protocol names are mapped by default.
"""

from __future__ import annotations

import argparse
import io
import sys
import tokenize
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Final

__all__ = ["DEFAULT_REPLACEMENTS", "Rule", "main", "unasync_source"]

