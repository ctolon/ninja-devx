_HEADER: Final = (
    "# Generated by `python -m ninja_devx.tooling.unasync` from:\n# {source}\n# Do not edit.\n"
)


@dataclass(frozen=True, slots=True)
class Rule:
    source: Path
    target: Path


def unasync_source(
    code: str, replacements: Mapping[str, str] = DEFAULT_REPLACEMENTS, *, header: str = ""
) -> str:
    """The sync version of ``code``."""
    lines = code.splitlines(keepends=True)
    offsets = [0]
    for line in lines:
        offsets.append(offsets[-1] + len(line))

    def position(row: int, column: int) -> int:
        return offsets[row - 1] + column

    edits: list[tuple[int, int, str]] = []
    tokens = list(tokenize.generate_tokens(io.StringIO(code).readline))
    for index, token in enumerate(tokens):
        if token.type != tokenize.NAME:
            continue
        start = position(*token.start)
        end = position(*token.end)
        following = tokens[index + 1] if index + 1 < len(tokens) else None
        if token.string == "await" or (
            token.string == "async"
            and following is not None
            and following.string in {"def", "for", "with"}
        ):
            next_start = position(*following.start) if following is not None else end
            edits.append((start, next_start, ""))
        elif (replacement := replacements.get(token.string)) is not None:
            edits.append((start, end, replacement))
    result = code
    for start, end, text in reversed(edits):
        result = result[:start] + text + result[end:]
    return header + result


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="python -m ninja_devx.tooling.unasync", description=__doc__
    )
    parser.add_argument("rules", nargs="+", metavar="ASYNC.py:SYNC.py")
    parser.add_argument("--check", action="store_true", help="fail when a target is outdated")
    parser.add_argument(
        "--replace", action="append", default=[], metavar="OLD=NEW", help="extra name mapping"
    )
    arguments = parser.parse_args(argv)
    replacements = dict(DEFAULT_REPLACEMENTS)
    for item in arguments.replace:
        old, separator, new = str(item).partition("=")
        if not separator:
            parser.error(f"--replace expects OLD=NEW, got {item!r}")
        replacements[old] = new
    outdated: list[Path] = []
    for raw in arguments.rules:
        source, separator, target = str(raw).partition(":")
        if not separator:
            parser.error(f"expected ASYNC.py:SYNC.py, got {raw!r}")
        rule = Rule(Path(source), Path(target))
        generated = unasync_source(
            rule.source.read_text(),
            replacements,
            header=_HEADER.format(source=rule.source.as_posix()),
        )
        current = rule.target.read_text() if rule.target.exists() else None
        if current == generated:
            continue
        if arguments.check:
            outdated.append(rule.target)
        else:
            rule.target.write_text(generated)
            print(f"wrote {rule.target}")
    if outdated:
        names = ", ".join(str(path) for path in outdated)
        print(f"outdated (run without --check): {names}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
